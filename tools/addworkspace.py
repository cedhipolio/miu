#!/usr/bin/env python3
"""Generate src/workspace.js (the pk-ws blob) from src/workspace/.

   python3 tools/addworkspace.py

src/workspace.js is GENERATED — edit the parts in src/workspace/ and run this:
   head.js     constants, the CSS every tab gets, the workspace page's own CSS
   align.js    the ribbon-alignment primitives (groups, natural sizes, merge, seats)
   main.js     tabs: making, dressing, look sync, showing, closing; the stamp-card CSS lift
   tail.js     alignment across tabs, the tab strip, start()
   switch.css  the MiU|RFDS switch and the logo swap (into head.js at @@CSS_PART@@)
   rfds-stamp.js  Mark It Up's COP stamp card, injected into every RFDS tab (@@RFDS_STAMP_JS@@, as a string)
   icons/*.b64    the alpha masks for the two tool marks and the swap arrows
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
W = os.path.join(HERE, "..", "src", "workspace")
OUT = os.path.join(HERE, "..", "src", "workspace.js")
rd = lambda n: open(os.path.join(W, n), encoding="utf-8").read()

head = rd("head.js").replace("@@CSS_PART@@", rd("switch.css").replace("${MODE_ICO.", "${ICO."))
js = head + rd("align.js") + rd("main.js") + rd("tail.js")
js = (js.replace("@@MIU_ICO@@", rd("icons/miu-mask.b64").strip())
        .replace("@@RFDS_ICO@@", rd("icons/rfds-mask.b64").strip())
        .replace("@@SWAP_ICO@@", rd("icons/swap-mask.b64").strip())
        .replace("@@RFDS_STAMP_JS@@", json.dumps(rd("rfds-stamp.js"))))
assert "@@" not in js, "an unfilled placeholder is left in the workspace"
banner = "/* GENERATED by tools/addworkspace.py from src/workspace/ — do not edit this file. */\n"
open(OUT, "w", encoding="utf-8").write(banner + js)
print(f"src/workspace.js  {len(js)/1024:.0f} KB")
