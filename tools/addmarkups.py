#!/usr/bin/env python3
"""Build src/markups-preset.js — the markups every user starts with — from a folder of PNGs.

Ced: "add these on pre loaded markup photos."

The drawings Ced supplied are red line art on transparency, some of them very large (one is
2460x4373 and 84 MB as delivered). Each is cropped to its ink, scaled so its long side is at most
1000 px (a markup is a couple of inches on a letter sheet: 1000 px is ~400 dpi there), and stored
as an adaptive-palette PNG with its alpha kept — line art in a few dozen colours loses nothing.

    python3 tools/addmarkups.py <folder of .png>      # writes src/markups-preset.js

The file name, less ".png", is the markup's name.
"""
import base64, io, json, pathlib, sys
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "markups-preset.js"
MAX = 1000


def pack(path):
    im = Image.open(path).convert("RGBA")
    bb = im.getbbox()
    if bb:
        pad = 4
        im = im.crop((max(0, bb[0] - pad), max(0, bb[1] - pad), min(im.width, bb[2] + pad), min(im.height, bb[3] + pad)))
    if max(im.size) > MAX:
        k = MAX / max(im.size)
        im = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
    q = im.quantize(colors=96, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    buf = io.BytesIO(); q.save(buf, "PNG", optimize=True)
    raw = buf.getvalue()
    return im.size, "data:image/png;base64," + base64.b64encode(raw).decode("ascii"), len(raw)


def main():
    src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "assets" / "markups")
    recs, total = [], 0
    for i, p in enumerate(sorted(src.glob("*.png"), key=lambda x: x.name.lower())):
        (w, h), url, n = pack(p)
        # keep the prepared copy in assets/markups so the library can be rebuilt from the repo alone
        dst = ROOT / "assets" / "markups" / p.name
        if p.resolve() != dst.resolve():
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(base64.b64decode(url.split(",", 1)[1]))
        recs.append({"id": "preset:" + p.stem.lower().replace(" ", "-"), "name": p.stem, "src": url,
                     "w": w, "h": h, "preset": True})
        total += n
        print(f"  {p.stem:22s} {w}x{h}  {n/1024:.0f} KB", file=sys.stderr)
    OUT.write_text(
        "/* GENERATED by tools/addmarkups.py from assets/markups/ — do not edit by hand.\n"
        "   v60 — the markups every user starts with (Ced: \"add these on pre loaded markup photos\").\n"
        "   Read by maRenderMarkupsTab; never written to browser storage. */\n"
        "var MA_PRESET_MARKUPS=" + json.dumps(recs, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"{len(recs)} markups, {total/1024:.0f} KB -> {OUT.relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
